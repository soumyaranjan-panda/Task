import { useEffect, useMemo, useState } from "react";
import { Link } from "@tanstack/react-router";
import { ArrowRight, BookOpen, FileCode2, History, Search } from "lucide-react";
import { APP } from "@/lib/app-config";
import {
  findPage,
  knownUnitCount,
  unitNoun,
  useManifest,
  type TopicMeta,
} from "@/lib/content/manifest";
import { loadAllStudied, loadRecentTopics, type RecentTopic } from "@/lib/progress";
import { useOpenSearch } from "@/lib/search-context";
import { topicIcon } from "./topic-icon";

const KIND_LABEL: Record<TopicMeta["kind"], string> = {
  "markdown-doc": "Guide",
  "markdown-book": "Handbook",
  "html-doc": "Interactive notes",
};

/** Best label for "resume" — the page title for books, otherwise generic. */
function resumeLabel(topic: TopicMeta, id: string): string {
  if (topic.kind === "markdown-book") return findPage(topic, id)?.title ?? "Continue reading";
  return "Continue reading";
}

/** Landing page: resume what you were reading, then browse every topic. */
export function HomeDashboard() {
  const { manifest, error } = useManifest();
  const [studiedByTopic, setStudiedByTopic] = useState<Record<string, string[]>>({});
  const [recent, setRecent] = useState<RecentTopic[]>([]);
  const openSearch = useOpenSearch();

  // Progress and recents live in localStorage, so they are only readable client-side.
  useEffect(() => {
    setStudiedByTopic(loadAllStudied());
    setRecent(loadRecentTopics());
  }, []);

  const topics = useMemo(() => manifest?.topics ?? [], [manifest]);
  const topicBySlug = useMemo(
    () => new Map(topics.map((topic) => [topic.slug, topic])),
    [topics],
  );
  const continuing = useMemo(
    () =>
      recent
        .map((entry) => ({ ...entry, topic: topicBySlug.get(entry.slug) }))
        .filter((entry): entry is RecentTopic & { topic: TopicMeta } => Boolean(entry.topic))
        .slice(0, 3),
    [recent, topicBySlug],
  );

  const totalStudied = topics.reduce(
    (sum, topic) => sum + (studiedByTopic[topic.slug]?.length ?? 0),
    0,
  );
  const totalUnits = topics.reduce((sum, topic) => sum + (knownUnitCount(topic) ?? 0), 0);

  return (
    <main className="flex-1 min-h-0 overflow-x-hidden overflow-y-auto">
      <div className="mx-auto w-full max-w-full max-w-5xl px-5 py-10 sm:px-8 sm:py-14">
        <section className="max-w-2xl">
          <h1 className="text-3xl font-semibold tracking-tight sm:text-4xl">{APP.name}</h1>
          <p className="mt-3 text-[15px] text-pretty text-muted">{APP.description}</p>

          <button
            type="button"
            onClick={openSearch}
            className="mt-6 inline-flex w-full flex-wrap items-center gap-2 rounded-lg border border-border bg-surface px-3 py-2.5 text-muted hover:bg-surface-2 hover:text-fg sm:w-auto sm:px-4 sm:py-3"
          >
            <Search size={17} />
            <span className="text-sm">Search every problem, section and page</span>
            <kbd className="ml-auto rounded border border-border px-1.5 py-0.5 text-[10px] text-faint sm:ml-2">
              ⌘K
            </kbd>
          </button>

          {topics.length > 0 ? (
            <dl className="mt-7 flex flex-wrap gap-x-8 gap-y-3">
              <Stat label="Subjects" value={topics.length} />
              {totalUnits > 0 ? <Stat label="Total items" value={totalUnits} /> : null}
              <Stat label="Ticked off" value={totalStudied} />
            </dl>
          ) : null}
        </section>

        {error ? (
          <p className="mt-10 rounded-lg border border-border bg-surface px-4 py-6 text-sm text-muted">
            {error}
            <span className="mt-2 block text-xs text-faint">
              Content is generated by <code>npm run sync</code> from{" "}
              <code>content.config.json</code>.
            </span>
          </p>
        ) : null}

        {!error && topics.length === 0 ? (
          <p className="mt-10 text-sm text-muted">Loading topics…</p>
        ) : null}

        {continuing.length > 0 ? (
          <section className="mt-12">
            <h2 className="flex items-center gap-2 text-xs font-medium uppercase tracking-[0.14em] text-faint">
              <History size={13} /> Pick up where you left off
            </h2>
            <div className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
              {continuing.map((entry) => {
                const Icon = topicIcon(entry.topic.icon);
                return (
                  <Link
                    key={entry.slug}
                    to="/topic/$topicSlug"
                    params={{ topicSlug: entry.slug }}
                    search={{ p: entry.id }}
                    className="group flex items-start gap-3 rounded-xl border border-border bg-surface p-4 transition-colors hover:border-border-strong hover:bg-surface-2"
                  >
                    <span className="grid size-9 shrink-0 place-items-center rounded-lg border border-border bg-bg text-primary">
                      <Icon size={17} />
                    </span>
                    <span className="min-w-0">
                      <span className="block truncate text-xs text-faint">{entry.topic.title}</span>
                      <span className="mt-0.5 block truncate text-sm font-medium text-fg">
                        {resumeLabel(entry.topic, entry.id)}
                      </span>
                      <span className="mt-1 inline-flex items-center gap-1 text-[11px] text-accent">
                        Resume <ArrowRight size={11} />
                      </span>
                    </span>
                  </Link>
                );
              })}
            </div>
          </section>
        ) : null}

        <section className="mt-12 grid gap-4 sm:grid-cols-2">
          {topics.map((topic) => (
            <TopicCard
              key={topic.slug}
              topic={topic}
              studiedCount={studiedByTopic[topic.slug]?.length ?? 0}
            />
          ))}
        </section>

        <p className="mt-14 text-xs text-faint">
          Content is generated from <code>content.config.json</code> — add a topic there and run{" "}
          <code>npm run sync</code>. Nothing here is duplicated: the app reads your original notes.
        </p>
      </div>
    </main>
  );
}

function Stat({ label, value }: { label: string; value: number }) {
  return (
    <div>
      <dt className="text-[11px] uppercase tracking-[0.12em] text-faint">{label}</dt>
      <dd className="mt-0.5 text-xl font-semibold tabular-nums">{value}</dd>
    </div>
  );
}

function TopicCard({ topic, studiedCount }: { topic: TopicMeta; studiedCount: number }) {
  const Icon = topicIcon(topic.icon);
  const units = knownUnitCount(topic);
  const percent = units ? Math.min(100, Math.round((studiedCount / units) * 100)) : null;
  const unitText = unitNoun(topic.units, units ?? 2);

  return (
    <Link
      to="/topic/$topicSlug"
      params={{ topicSlug: topic.slug }}
      className="group flex flex-col rounded-xl border border-border bg-surface p-5 transition-colors hover:border-border-strong hover:bg-surface-2"
    >
      <div className="flex items-start gap-3">
        <span className="grid size-10 shrink-0 place-items-center rounded-lg border border-border bg-bg text-primary">
          <Icon size={20} />
        </span>
        <div className="min-w-0 flex-1">
          <h2 className="truncate font-medium leading-tight">{topic.title}</h2>
          <p className="truncate text-xs text-muted">{topic.subtitle ?? KIND_LABEL[topic.kind]}</p>
        </div>
        <ArrowRight
          size={18}
          className="mt-1 shrink-0 text-faint transition-colors group-hover:text-fg"
        />
      </div>

      {topic.summary ? (
        <p className="mt-3 text-sm text-pretty text-muted">{topic.summary}</p>
      ) : null}

      <div className="mt-4 flex items-center gap-2 text-[11px] text-faint">
        <span className="inline-flex items-center gap-1">
          {topic.kind === "html-doc" ? <FileCode2 size={12} /> : <BookOpen size={12} />}
          {KIND_LABEL[topic.kind]}
        </span>
        {units ? (
          <span>
            · {units} {unitText}
          </span>
        ) : null}
      </div>

      {percent !== null ? (
        <div className="mt-4">
          <div className="h-1.5 overflow-hidden rounded-full bg-surface-2">
            <div className="h-full rounded-full bg-primary" style={{ width: `${percent}%` }} />
          </div>
          <p className="mt-2 text-[11px] tabular-nums text-muted">
            {studiedCount} of {units} {unitText} studied
          </p>
        </div>
      ) : null}
    </Link>
  );
}
